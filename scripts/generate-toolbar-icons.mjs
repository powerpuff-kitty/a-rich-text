import * as icons from '@fortawesome/free-solid-svg-icons';
import { readFile, writeFile } from 'node:fs/promises';
const manifest = JSON.parse(await readFile('node_modules/@fortawesome/free-solid-svg-icons/package.json', 'utf8'));
const names = {
  bold: 'faBold', italic: 'faItalic', underline: 'faUnderline', strike: 'faStrikethrough', code: 'faCode',
  link: 'faLink', 'bullet-list': 'faListUl', 'ordered-list': 'faListOl', 'task-list': 'faListCheck',
  blockquote: 'faQuoteLeft', 'horizontal-rule': 'faMinus', 'clear-formatting': 'faEraser',
  indent: 'faIndent', outdent: 'faOutdent', 'insert-table': 'faTable',
  row: 'faTableList', column: 'faTableColumns', plus: 'faPlus', minus: 'faMinus', undo: 'faRotateLeft', redo: 'faRotateRight',
};
const selected = Object.fromEntries(Object.entries(names).map(([name, exportName]) => {
  const icon = icons[exportName];
  if (!icon) throw new Error(`Missing Font Awesome icon ${exportName}`);
  const [width, height, , , data] = icon.icon;
  return [name, { width, height, paths: Array.isArray(data) ? data : [data] }];
}));
const notice = `Font Awesome Free ${manifest.version} by Fonticons, Inc. — https://fontawesome.com\nIcons: CC BY 4.0; source: @fortawesome/free-solid-svg-icons.\nSelected paths are unmodified; row/column actions compose separate icons.\nhttps://fontawesome.com/license/free\n\n`;
const license = await readFile('node_modules/@fortawesome/free-solid-svg-icons/LICENSE.txt', 'utf8');
await writeFile('packages/ui/THIRD_PARTY_NOTICES.txt', notice + license);
await writeFile('packages/ui/src/icons.ts', `/** Generated by scripts/generate-toolbar-icons.mjs.\n * Font Awesome Free ${manifest.version} — https://fontawesome.com\n * Icons: CC BY 4.0. See THIRD_PARTY_NOTICES.txt.\n */\nconst icons = ${JSON.stringify(selected, null, 2)} as const;\n
export function toolbarIcon(name: string): string {
  if (name === 'add-row' || name === 'remove-row' || name === 'add-column' || name === 'remove-column') {
    return '<span class="icon-pair">' + toolbarIcon(name.endsWith('row') ? 'row' : 'column')
      + toolbarIcon(name.startsWith('add') ? 'plus' : 'minus') + '</span>';
  }
  const icon = icons[name as keyof typeof icons];
  if (!icon) return '';
  return '<svg aria-hidden="true" focusable="false" viewBox="0 0 ' + icon.width + ' ' + icon.height + '">'
    + icon.paths.map(path => '<path fill="currentColor" d="' + path + '"></path>').join('') + '</svg>';
}
`);
